from datalens.data import profile
from datalens.diagnostics import VIF_HIGH, Diagnostics, DiagnosticsError, diagnose
from datalens.eda import describe_numeric
from datalens.formatting import fmt_num, fmt_pvalue
from datalens.plots import cv_error_figure, qq_plot, residuals_vs_fitted, scale_location
from datalens.regression import RegressionResult

# Western Indonesia Time: a fixed UTC+7 with no daylight saving, so a fixed
# offset is exact and needs no tzdata (which zoneinfo lacks on Windows).
# The deployed server runs on UTC, so report times must not use naive now().
WIB = timezone(timedelta(hours=7), "WIB")


def now_wib() -> datetime:
    return datetime.now(WIB)


def to_wib(when: datetime) -> datetime:
    """Convert to WIB. Naive datetimes are read as the machine's local time
    (Python's ``astimezone`` rule), which is what a naive ``now()`` means."""
    return when.astimezone(WIB)


@dataclass(frozen=True)
class ReportInputs:
    dataset_name: str
    df: pd.DataFrame
    result: RegressionResult
    comparison: ComparisonResult | None = None
    include_figures: bool = True
    generated_at: datetime = field(default_factory=now_wib)


# --- Rule-based text -------------------------------------------------------------


def coefficient_findings(r: RegressionResult) -> list[str]:
    """One plain-language sentence per slope, worded as association."""
    pct = f"{r.conf_level:.0%}"
    held = "Dengan prediktor lain dalam model dibuat tetap, kenaikan" if len(r.predictors) > 1 else "Kenaikan"
    out = []
    for name in r.predictors:
        row = r.coefficients.loc[name]
        covers_zero = row.ci_lower <= 0 <= row.ci_upper
        out.append(
            f"{name}: {held} 1 unit {name} berasosiasi dengan perubahan rata-rata {fmt_num(row.estimate)} "
            f"unit pada {r.target} (CI {pct}: {fmt_num(row.ci_lower)} sampai {fmt_num(row.ci_upper)}; "
            f"p {_p_inline(row.p_value)}). Interval ini {'mencakup' if covers_zero else 'tidak mencakup'} nol."
        )
    return out


def fit_finding(r: RegressionResult) -> str:
    return (
        f"Model menjelaskan {r.r_squared:.1%} variasi {r.target} dalam sampel (adjusted R² = "
        f"{fmt_num(r.adj_r_squared)}). Ini ukuran kecocokan dalam sampel, bukan akurasi prediksi pada data baru."
    )


def limitations(r: RegressionResult, diag: Diagnostics | None, cmp: ComparisonResult | None) -> list[str]:
    items = [
        "Hasil menggambarkan asosiasi, bukan hubungan sebab-akibat. Variabel perancu yang tidak diamati dapat "
        "menjelaskan hubungan yang terlihat.",
        "Galat baku dan interval kepercayaan memakai rumus OLS klasik, yang mengasumsikan galat independen "
        "dengan varians konstan.",
    ]
    items += list(r.warnings)
    if diag is None:
        items.append("Diagnostik residual tidak tersedia untuk model ini, sehingga asumsi model tidak dapat diperiksa.")
        return items

    bp, normality, reset = diag.tests
    if bp.available and bp.p_value < bp.alpha:
        items.append(
            "Uji Breusch–Pagan menunjukkan bukti heteroskedastisitas. Galat baku klasik, p-value, dan interval "
            "kepercayaan mungkin tidak akurat. Galat baku robust (misalnya HC3) dapat dipertimbangkan."
        )
    if reset.available and reset.p_value < reset.alpha:
        items.append(
            "Uji RESET menunjukkan bukti nonlinearitas yang belum dimodelkan. Slope linear mungkin meringkas "
            "hubungan yang sebenarnya melengkung. Periksa plot residual vs nilai prediksi."
        )
    if normality.available and normality.p_value < normality.alpha and r.n_obs < 30:
        items.append(
            "Ada bukti galat tidak normal pada sampel kecil, sehingga p-value dan interval kepercayaan bisa tidak akurat."
        )
    for t in diag.tests:
        if not t.available:
            items.append(f"Uji {t.test} tidak dijalankan: {t.note}")
    if diag.vif is not None and (diag.vif["vif"] >= VIF_HIGH).any():
        high = ", ".join(diag.vif.index[diag.vif["vif"] >= VIF_HIGH])
        items.append(
            f"VIF ≥ {VIF_HIGH:g} untuk {high}: estimasi koefisien individual tidak presisi karena multikolinearitas."
        )
    if len(diag.influential):
        items.append(
            f"{len(diag.influential)} observasi melewati ambang praktis untuk pengaruh/leverage/residual ekstrem. "
            "Hasil sebaiknya diperiksa ulang dengan dan tanpa observasi tersebut."
        )
    items += list(diag.notes)
    if cmp is not None:
        items.append(
            "SD galat validasi silang menggambarkan variasi antar-fold, bukan galat baku. Fold berbagi data latih."
        )
    return items


# --- HTML building blocks --------------------------------------------------------


def _e(value: object) -> str:
    return html.escape(str(value), quote=True)


def _v(key: str, text: str) -> str:
    """A reported value, tagged for verification."""
    return f'<span class="v" data-key="{_e(key)}">{_e(text)}</span>'


def _p_inline(p: float) -> str:
    s = fmt_pvalue(p)
    return s if s.startswith("<") else f"= {s}"


def _table(header: list[str], rows: list[list[str]], numeric: set[int] | None = None) -> str:
    """rows contain already-escaped HTML cells. ``numeric`` = column indices to right-align
    (default: every column after the first)."""
    numeric = set(range(1, len(header))) if numeric is None else numeric
    head = "".join(f'<th class="{"num" if i in numeric else ""}">{_e(h)}</th>' for i, h in enumerate(header))
    body = "".join(
        "<tr>" + "".join(
            f'<td class="{"num" if i in numeric else ""}">{cell}</td>' for i, cell in enumerate(row)
        ) + "</tr>"
        for row in rows
    )
    return f'<div class="table-wrap"><table><thead><tr>{head}</tr></thead><tbody>{body}</tbody></table></div>'


def _figure(fig: go.Figure, title: str, caption: str = "") -> str:
    fig = go.Figure(fig)
    fig.update_layout(template="plotly_white", paper_bgcolor="white", plot_bgcolor="white")
    div = fig.to_html(full_html=False, include_plotlyjs=False, config={"displaylogo": False, "responsive": True})
    cap = f"<figcaption>{_e(caption)}</figcaption>" if caption else ""
    return f'<figure><h4>{_e(title)}</h4>{div}{cap}</figure>'


def _list(items: list[str]) -> str:
    return "<ul>" + "".join(f"<li>{_e(i)}</li>" for i in items) + "</ul>"


# --- Sections --------------------------------------------------------------------


def _dataset_section(name: str, df: pd.DataFrame, r: RegressionResult) -> str:
    p = profile(df)
    desc = describe_numeric(df, [r.target, *r.predictors])
    rows = [
        [_e(var)] + [
            _v(f"desc:{var}:{col}", fmt_num(desc.loc[var, col]) if col not in ("n", "n_hilang") else str(int(desc.loc[var, col])))
            for col in ("n", "n_hilang", "mean", "sd", "min", "median", "max")
        ]
        for var in desc.index
    ]
    return f"""
<section>
  <h2>1. Dataset</h2>
  <p>File <strong>{_e(name)}</strong>: {_v("rows", f"{p.n_rows:,}")} baris, {_v("cols", str(p.n_cols))} kolom
  ({p.n_numeric} numerik). {_v("rows_missing", f"{p.n_rows_with_missing:,}")} baris memiliki minimal satu nilai
  hilang, dan terdapat {_v("duplicates", f"{p.n_duplicate_rows:,}")} baris duplikat (tidak dihapus otomatis).</p>
  <h3>Statistik deskriptif variabel model</h3>
  {_table(["Variabel", "n", "Hilang", "Mean", "SD", "Min", "Median", "Max"], rows)}
  <p class="note">SD memakai pembagi n − 1. Statistik dihitung per kolom dari nilai yang tersedia.</p>
</section>"""


def _model_section(r: RegressionResult) -> str:
    pct = f"{r.conf_level:.0%}"
    coef_rows = [
        [_e(term)] + [
            _v(f"coef:{term}:{col}", fmt_pvalue(r.coefficients.loc[term, col]) if col == "p_value"
               else fmt_num(r.coefficients.loc[term, col]))
            for col in ("estimate", "std_error", "t_value", "p_value", "ci_lower", "ci_upper")
        ]
        for term in r.coefficients.index
    ]
    return f"""
<section>
  <h2>2. Spesifikasi dan hasil model</h2>
  <dl class="spec">
    <dt>Model</dt><dd><code>{_e(formula(r.target, r.predictors))}</code> (OLS dengan intersep)</dd>
    <dt>Observasi dipakai</dt><dd>{_v("n_obs", f"{r.n_obs:,}")} (dikeluarkan: {_v("n_dropped", str(r.n_dropped))},
      complete-case pada variabel model)</dd>
    <dt>Galat baku</dt><dd>Klasik (non-robust); interval kepercayaan {_e(pct)}</dd>
  </dl>
  <p class="equation">{_v("equation", r.equation)}</p>
  <div class="stats">
    <div><span class="label">R²</span>{_v("r_squared", fmt_num(r.r_squared))}</div>
    <div><span class="label">Adjusted R²</span>{_v("adj_r_squared", fmt_num(r.adj_r_squared))}</div>
    <div><span class="label">Galat baku residual</span>{_v("residual_std_error", fmt_num(r.residual_std_error))}</div>
    <div><span class="label">Uji F ({r.df_model}, {r.df_resid})</span>{_v("f_statistic", fmt_num(r.f_statistic))}
      <small>p {_v("f_pvalue", _p_inline(r.f_pvalue))}</small></div>
  </div>
  {_table(["Term", "Estimasi", "Galat baku", "t", "p-value", f"CI {pct} bawah", f"CI {pct} atas"], coef_rows)}
  <h3>Temuan utama</h3>
  {_list([fit_finding(r), *coefficient_findings(r)])}
  <p class="note">p-value bukan probabilitas bahwa H0 benar. Signifikansi statistik tidak sama dengan
  kepentingan praktis: nilailah besar efek dari koefisien dan intervalnya dalam satuan aslinya.</p>
</section>"""


def _diagnostics_section(diag: Diagnostics | None, reason: str, include_figures: bool) -> str:
    if diag is None:
        return f'<section><h2>3. Diagnostik model</h2><p>Tidak tersedia: {_e(reason)}</p></section>'
    test_rows = [
        [
            _e(t.assumption), _e(t.test),
            _v(f"test:{i}:statistic", fmt_num(t.statistic) if t.available else "—"),
            _e(t.df or "—"),
            _v(f"test:{i}:p_value", fmt_pvalue(t.p_value) if t.available else "—"),
            _e(t.conclusion),
        ]
        for i, t in enumerate(diag.tests)
    ]
    vif_html = (
        _table(["Prediktor", "VIF", "Tingkat"],
               [[_e(n), _v(f"vif:{n}", fmt_num(row.vif)), _e(row.tingkat)] for n, row in diag.vif.iterrows()],
               numeric={1})
        if diag.vif is not None
        else "<p>VIF tidak relevan untuk model dengan satu prediktor.</p>"
    )
    figures = ""
    if include_figures:
        figures = '<div class="figs">' + "".join([
            _figure(residuals_vs_fitted(diag), "Residual vs nilai prediksi",
                    "Diharapkan: sebaran acak di sekitar 0. Lengkungan menandakan nonlinearitas, corong menandakan heteroskedastisitas."),
            _figure(scale_location(diag), "Scale-location", "Diharapkan: tren LOWESS kira-kira datar."),
            _figure(qq_plot(diag), "Normal Q-Q plot", "Diharapkan: titik mengikuti garis acuan."),
        ]) + "</div>"
    return f"""
<section>
  <h2>3. Diagnostik model</h2>
  <p>Plot adalah alat utama. Uji formal hanya bukti pendukung, dan p ≥ α <strong>tidak</strong> membuktikan asumsi
  terpenuhi.</p>
  {figures}
  <h3>Uji formal (α = 0.05)</h3>
  {_table(["Asumsi", "Uji", "Statistik", "df", "p-value", "Kesimpulan"], test_rows, numeric={2, 3, 4})}
  <p>Durbin–Watson = {_v("durbin_watson", f"{diag.durbin_watson:.3f}")}. Statistik ini hanya bermakna bila urutan
  baris memiliki arti (misalnya waktu).</p>
  <h3>Multikolinearitas</h3>
  {vif_html}
  <p>Condition number (terskala, termasuk intersep) = {_v("condition_number", fmt_num(diag.condition_number, 3))}.</p>
  <h3>Observasi berpengaruh</h3>
  <p>{_v("n_influential", str(len(diag.influential)))} observasi ditandai (Cook's D &gt; 4/n, leverage &gt; 2p/n, atau
  |residual terstudentisasi eksternal| &gt; 3). Ambang ini aturan praktis, bukan alasan untuk menghapus data.</p>
</section>"""


def _comparison_section(c: ComparisonResult, include_figures: bool) -> str:
    in_rows = [
        [_e(name), f"<code>{_e(row.formula)}</code>",
         _v(f"cmp:{name}:r_squared", fmt_num(row.r_squared)),
         _v(f"cmp:{name}:adj_r_squared", fmt_num(row.adj_r_squared)),
         _v(f"cmp:{name}:aic", f"{row.aic:.2f}"), _v(f"cmp:{name}:bic", f"{row.bic:.2f}")]
        for name, row in c.in_sample.iterrows()
    ]
    s = c.cv_summary
    cv_rows = [
        [_e(m),
         _v(f"cv:{m}:rmse_mean", fmt_num(s.loc[m, "rmse_mean"])), _v(f"cv:{m}:rmse_std", fmt_num(s.loc[m, "rmse_std"], 3)),
         _v(f"cv:{m}:mae_mean", fmt_num(s.loc[m, "mae_mean"])), _v(f"cv:{m}:mae_std", fmt_num(s.loc[m, "mae_std"], 3))]
        for m in s.index
    ]
    a, b = c.names
    lower = b if s.loc[b, "rmse_mean"] < s.loc[a, "rmse_mean"] else a
    nested = (
        f"<p>Uji F parsial: F({c.nested_f.df_num}, {c.nested_f.df_denom}) = "
        f"{_v('nested_f', fmt_num(c.nested_f.f_statistic))}, p {_v('nested_p', _p_inline(c.nested_f.p_value))}.</p>"
        if c.nested_f else "<p>Uji F parsial tidak berlaku (model tidak bersarang).</p>"
    )
    fig = _figure(cv_error_figure(c), "RMSE per split validasi silang") if include_figures else ""
    return f"""
<section>
  <h2>4. Perbandingan model</h2>
  <p>Variabel dependen <code>{_e(c.target)}</code>. Semua model dievaluasi pada {_v("cmp_n", f"{c.n_obs:,}")} baris
  yang sama. Validasi silang: {c.n_splits}-fold × {c.n_repeats} pengulangan (seed {c.seed}), dengan split identik
  untuk semua model.</p>
  <h3>Kecocokan dalam sampel</h3>
  {_table(["Model", "Spesifikasi", "R²", "Adj. R²", "AIC", "BIC"], in_rows, numeric={2, 3, 4, 5})}
  {nested}
  <h3>Galat prediksi di luar sampel</h3>
  {_table(["Model", "RMSE rata-rata", "SD", "MAE rata-rata", "SD"], cv_rows)}
  {fig}
  <p>Rata-rata RMSE validasi silang lebih rendah pada model {_e(lower)}. RMSE model B lebih rendah daripada A pada
  {_v("share_b_better", f"{(c.paired_rmse_diff < 0).mean():.0%}")} dari {len(c.paired_rmse_diff)} split. Pembanding:
  {_e(BASELINE)} = model yang selalu memprediksi rata-rata data latih.</p>
  <p class="note">R² dalam sampel selalu naik saat prediktor ditambahkan. Hanya galat pada data yang tidak dipakai
  untuk estimasi yang menunjukkan kinerja prediksi.</p>
</section>"""


