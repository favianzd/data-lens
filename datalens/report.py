def build_report(inputs: ReportInputs) -> str:
    r = inputs.result
    try:
        diag, reason = diagnose(r), ""
    except DiagnosticsError as exc:
        diag, reason = None, str(exc)

    sections = [
        _dataset_section(inputs.dataset_name, inputs.df, r),
        _model_section(r),
        _diagnostics_section(diag, reason, inputs.include_figures),
    ]
    if inputs.comparison is not None:
        sections.append(_comparison_section(inputs.comparison, inputs.include_figures))
    n_lim = len(sections) + 1
    sections.append(
        f'<section><h2>{n_lim}. Keterbatasan</h2>{_list(limitations(r, diag, inputs.comparison))}</section>'
    )

    plotly_js = (
        f"<script>{plotly.offline.get_plotlyjs()}</script>" if inputs.include_figures else ""
    )
    versions = (
        f"Python {platform.python_version()}, pandas {pd.__version__}, NumPy {np.__version__}, "
        f"statsmodels {statsmodels.__version__}, SciPy {scipy.__version__}, scikit-learn {sklearn.__version__}, "
        f"Plotly {plotly.__version__}"
    )
    stamp = to_wib(inputs.generated_at).strftime("%Y-%m-%d %H:%M %Z")
    return f"""<!doctype html>
<html lang="id">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Laporan DataLens: {_e(inputs.dataset_name)}</title>
<style>{CSS}</style>
{plotly_js}
</head>
<body>
<main>
<header>
  <h1>Laporan Analisis Regresi</h1>
  <div class="meta">Dataset: <strong>{_e(inputs.dataset_name)}</strong> · Dibuat {_e(stamp)} dengan DataLens {__version__}</div>
</header>
<p>Laporan ini dibuat otomatis dari hasil analisis di DataLens. Semua angka berasal langsung dari model yang
diestimasi. Kalimat temuan dan keterbatasan disusun dari hasil tersebut dan perlu ditinjau oleh analis
sebelum dipakai.</p>
{''.join(sections)}
<footer class="meta">Perangkat lunak: {_e(versions)}.</footer>
</main>
</body>
</html>"""


def report_filename(dataset_name: str, when: datetime) -> str:
    stem = "".join(ch if ch.isalnum() or ch in "-_" else "_" for ch in dataset_name.rsplit(".", 1)[0])[:40]
    return f"datalens_laporan_{stem or 'dataset'}_{to_wib(when):%Y%m%d_%H%M}_WIB.html"
