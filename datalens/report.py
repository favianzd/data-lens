"""Self-contained HTML analysis report.

Every number in the report is read from the same result objects the app
displays (RegressionResult, Diagnostics, ComparisonResult) and formatted with
datalens.formatting. Nothing is recomputed or typed in by hand. Key values carry a
``data-key`` attribute so tests can check them against the underlying results.

Findings and limitations are generated by rules over those results. A
sentence appears only if the data supports it (e.g. the heteroscedasticity
caveat only when Breusch–Pagan rejects).
"""

from __future__ import annotations

import html
import platform
from dataclasses import dataclass, field
from datetime import datetime, timedelta, timezone

import numpy as np
import pandas as pd
import plotly
import plotly.graph_objects as go
import plotly.offline
import scipy
import sklearn
import statsmodels

from datalens import __version__
